# 按性质获取格局列表的函数
def get_geju_by_nature(nature):
    """
    按性质获取格局列表
    
    :param nature: 格局性质，可选值为"吉"、"凶"、"中"
    :return: 指定性质的格局列表
    """
    result = []
    for (天盘干, 地盘干), 格局数据 in GEJU_DATA.items():
        if 格局数据["性质"] == nature:
            result.append((天盘干, 地盘干, 格局数据["名称"]))
    return result

# 获取特定天干地盘干组合的格局
def get_geju_by_gans(tian_pan_gan, di_pan_gan):
    """
    获取特定天干地盘干组合的格局
    
    :param tian_pan_gan: 天盘干
    :param di_pan_gan: 地盘干
    :return: 对应的格局数据字典，如果不存在则返回None
    """
    return GEJU_DATA.get((tian_pan_gan, di_pan_gan))

