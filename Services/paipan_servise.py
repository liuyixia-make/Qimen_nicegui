                地盘干 = 宫位数据.get("地盘干", "")
                宫支列表 = 宫位数据.get("宫支", [])
                长生列表 = []
                for 宫支 in 宫支列表:
                    if 地盘干 and 宫支:
                        长生状态 = self.长生状态表.get(地盘干, {}).get(宫支, "")
                        长生列表.append(长生状态)
                    else:
                        长生列表.append("")
                宫位数据["地盘干长生"] = 长生列表
                
                # 计算寄地盘干长生
                寄地盘干 = 宫位数据.get("寄地盘干", "")
                寄长生列表 = []
                for 宫支 in 宫支列表:
                    if 寄地盘干 and 宫支:
                        寄长生状态 = self.长生状态表.get(寄地盘干, {}).get(宫支, "")
                        寄长生列表.append(寄长生状态)
