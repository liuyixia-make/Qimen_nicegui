    def 排天盘干(self):
        """
        排列天盘干的方法
        1. 复制地盘干的顺序组合
        2. 取旬首值的最后一个字（值符天干A）
        3. 取时柱的天干（B）
        4. 在地盘干中找到B所在的宫位
        5. 将A放到B所在宫位的天盘干位置
        6. 按照"92761834"环形顺序旋转天盘
        
        特殊情况：
        - 当时柱天干为甲时，落在与旬首相同的天干上
        - 当时柱天干位于五宫时，将值符天干放在二宫位置
        - 当值符天干位于五宫时，将其放在二宫位置
        然后按正常逻辑排列
        
        注意：五宫（中宫）不参与天盘干排布，只有地盘干
        """
        # 获取必要的数据
        旬首 = self.奇门遁甲数据["起局信息"]["旬首"]
        if not 旬首 or len(旬首) < 3:
            print("警告：旬首数据不完整，无法排天盘干")
            return False
            
        # 获取值符天干（A）- 旬首的最后一个字
        值符天干 = 旬首[-1]
        
        # 获取时柱天干（B）
        时柱 = self.奇门遁甲数据["起局信息"]["四柱干支"][3]
        时柱天干 = 时柱[0]
        
        # 奇门九宫顺序："92761834"（按圈排列）
        奇门九宫顺序 = ["九宫", "二宫", "七宫", "六宫", "一宫", "八宫", "三宫", "四宫"]
        
        # 复制地盘干的顺序组合
        地盘干分布 = {}
        寄地盘干分布 = {}  # 新增：用于跟踪寄地盘干
        for 宫位键 in ["一宫", "二宫", "三宫", "四宫", "五宫", "六宫", "七宫", "八宫", "九宫"]:
            if 宫位键 in self.奇门遁甲数据:
                地盘干 = self.奇门遁甲数据[宫位键].get("地盘干", "")
                地盘干分布[宫位键] = 地盘干
                
                # 新增：记录寄地盘干
                寄地盘干 = self.奇门遁甲数据[宫位键].get("寄地盘干", "")
                寄地盘干分布[宫位键] = 寄地盘干
        
        # 特殊处理：当时柱天干为甲时，落在与旬首相同的天干上
        if 时柱天干 == "甲":
            # 获取旬首相同的天干
            旬首天干 = 旬首[0]  # 取旬首第一个字
            if 旬首天干 == "甲":
                # 如果旬首也是甲，则找到旬首最后一个字（值符天干）在地盘干中的宫位
                时柱天干宫位 = None
                for 宫位键, 地盘干 in 地盘干分布.items():
                    if 地盘干 == 值符天干:
                        时柱天干宫位 = 宫位键
                        break
                print(f"时柱天干为甲，落在与旬首值符天干 {值符天干} 相同的宫位")
            else:
                print(f"警告：旬首天干 {旬首天干} 不是甲，无法确定甲时的落宫")
                return False
        else:
            # 找到时柱天干（B）在地盘干中的宫位
            时柱天干宫位 = None
            for 宫位键, 地盘干 in 地盘干分布.items():
                if 地盘干 == 时柱天干:
                    时柱天干宫位 = 宫位键
                    break
                
        if not 时柱天干宫位:
            print(f"警告：找不到时柱天干 {时柱天干} 在地盘干中的宫位")
            return False
            
        # 找到值符天干（A）在地盘干中的宫位
        值符天干宫位 = None
        for 宫位键, 地盘干 in 地盘干分布.items():
            if 地盘干 == 值符天干:
                值符天干宫位 = 宫位键
                break
                
        if not 值符天干宫位:
            print(f"警告：找不到值符天干 {值符天干} 在地盘干中的宫位")
            return False
        
        # 特殊情况处理：当时干或值符天干在五宫时
        if 时柱天干宫位 == "五宫":
            print(f"检测到时干在五宫的特殊情况，将值符星放在二宫")
            时柱天干宫位 = "二宫"  # 时干在五宫时，使用二宫作为时干宫位
            
        if 值符天干宫位 == "五宫":
            print(f"检测到值符天干在五宫的特殊情况，将值符天干宫位设为二宫")
            值符天干宫位 = "二宫"  # 五宫值符特殊处理，将值符天干宫位设为二宫
        
        # 计算需要旋转的步数（A到B）
        if 值符天干宫位 in 奇门九宫顺序 and 时柱天干宫位 in 奇门九宫顺序:
            值符天干索引 = 奇门九宫顺序.index(值符天干宫位)
            时柱天干索引 = 奇门九宫顺序.index(时柱天干宫位)
            旋转步数 = (时柱天干索引 - 值符天干索引) % len(奇门九宫顺序)
        else:
            print(f"警告：值符天干宫位 {值符天干宫位} 或时柱天干宫位 {时柱天干宫位} 不在奇门九宫顺序中")
            return False
            
        # 按照"92761834"顺序旋转天盘
        天盘干分布 = {}
        寄天盘干分布 = {}  # 新增：用于跟踪寄天盘干的旋转
        for i, 宫位键 in enumerate(奇门九宫顺序):
            原宫位索引 = (i - 旋转步数) % len(奇门九宫顺序)
            原宫位键 = 奇门九宫顺序[原宫位索引]
            
            if 原宫位键 in 地盘干分布:
                天盘干 = 地盘干分布[原宫位键]
                天盘干分布[宫位键] = 天盘干
                
                # 新增：同时旋转寄地盘干到寄天盘干
                寄地盘干 = 寄地盘干分布[原宫位键]
                寄天盘干分布[宫位键] = 寄地盘干
        
        # 更新天盘干和寄天盘干到奇门遁甲数据
        for 宫位键, 天盘干 in 天盘干分布.items():
            if 宫位键 in self.奇门遁甲数据 and 宫位键 != "五宫":  # 确保不给五宫设置天盘干
                self.奇门遁甲数据[宫位键]["天盘干"] = 天盘干
                
                # 新增：更新寄天盘干
                if 宫位键 in 寄天盘干分布:
                    寄天盘干 = 寄天盘干分布[宫位键]
                    if 寄天盘干:  # 只在有值时更新
                        self.奇门遁甲数据[宫位键]["寄天盘干"] = 寄天盘干
                        print(f"将寄地盘干 {寄天盘干} 旋转到 {宫位键} 的寄天盘干")
                
                # 计算天盘干长生
                宫位数据 = self.奇门遁甲数据[宫位键]
                宫支列表 = 宫位数据.get("宫支", [])
                长生列表 = []
                for 宫支 in 宫支列表:
                    if 天盘干 and 宫支:
                        长生状态 = self.长生状态表.get(天盘干, {}).get(宫支, "")
                        长生列表.append(长生状态)
                    else:
                        长生列表.append("")
                宫位数据["天盘干长生"] = 长生列表
                
                # 新增：计算寄天盘干长生
                if 宫位键 in 寄天盘干分布:
                    寄天盘干 = 寄天盘干分布[宫位键]
                    if 寄天盘干:  # 只在有值时计算
                        寄长生列表 = []
                        for 宫支 in 宫支列表:
                            if 寄天盘干 and 宫支:
                                寄长生状态 = self.长生状态表.get(寄天盘干, {}).get(宫支, "")
                                寄长生列表.append(寄长生状态)
                            else:
                                寄长生列表.append("")
                        宫位数据["寄天盘干长生"] = 寄长生列表
        
        # 确保五宫的天盘干为空
        if "五宫" in self.奇门遁甲数据:
            self.奇门遁甲数据["五宫"]["天盘干"] = ""
            self.奇门遁甲数据["五宫"]["寄天盘干"] = ""
            self.奇门遁甲数据["五宫"]["天盘干长生"] = [""]
            self.奇门遁甲数据["五宫"]["寄天盘干长生"] = [""]
                
        return True

