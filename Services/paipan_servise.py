                # 新增：判断门迫
                天盘门 = 宫位数据.get("天盘门", "")
                if 天盘门:
                    # 获取门的五行属性
                    门五行 = ""
                    if "开门" in 天盘门 or "惊门" in 天盘门:
                        门五行 = "金"
                    elif "休门" in 天盘门:
                        门五行 = "水"
                    elif "生门" in 天盘门 or "死门" in 天盘门:
                        门五行 = "土"
                    elif "伤门" in 天盘门 or "杜门" in 天盘门:
                        门五行 = "木"
                    elif "景门" in 天盘门:
                        门五行 = "火"
                    
